"""Generate exact Fraction fee expectations; never import the Daml algorithm."""

from fractions import Fraction
from importlib.util import module_from_spec, spec_from_file_location
from pathlib import Path
import argparse

ROOT = Path(__file__).resolve().parent.parent
TARGET = ROOT / "contracts/test/daml/Outcomia/FeeVectors.daml"
spec = spec_from_file_location("fee_reference", ROOT / "scripts/check-fee-policy.py")
reference = module_from_spec(spec)
spec.loader.exec_module(reference)


def decimal(value):
    units = value * 10**10
    assert units.denominator == 1
    whole, fraction = divmod(int(units), 10**10)
    return f"{whole}.{str(fraction).zfill(10).rstrip('0') or '0'}"


def generate():
    notionals = list(map(Fraction, ["0", "0.0000000001", "0.0002", "0.01",
        "0.9999999999", "1.2345678901", "9223372036854775807"]))
    rows = []
    for precision in range(11):
        for bps in [0, 1, 25, 1000]:
            for notional in notionals:
                expected = reference.fee(notional, bps, Fraction(1, 10**precision))
                rows.append(f"({precision}, {bps}, {decimal(notional)}, {decimal(expected)})")
    return (
        "-- Generated by scripts/generate-fee-vectors.py from exact Python Fraction arithmetic.\n"
        "-- Check with --check; edit the generator/reference rather than this file.\n"
        "module Outcomia.FeeVectors where\n\n"
        "feeVectors : [(Int, Int, Decimal, Decimal)]\n"
        "feeVectors =\n  [ " + "\n  , ".join(rows) + "\n  ]\n"
    )


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    expected = generate()
    if args.check:
        if not TARGET.exists() or TARGET.read_text() != expected:
            raise SystemExit("Fee vectors differ: regenerate with scripts/generate-fee-vectors.py")
        print("PASS: 308 exact-rational fee vectors match the checked-in fixture.")
    else:
        TARGET.write_text(expected)
        print("Wrote 308 exact-rational fee vectors.")
